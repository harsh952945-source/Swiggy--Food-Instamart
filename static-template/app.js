  var STOP = ('i me my we you a an the for to of in on at and or with without want need get give show tell find some any something please can could would should what which whats is are am be do does have has eat order food dish dishes item items option options recommend recommendation suggest suggestion suggestions hungry craving cravings looking like love try best top good great nice tasty cheap cheaper cheapest budget popular under below less than within upto up max rs inr rupees veg vegetarian non nonveg today tonight now near here there it that this one few more quick fast grocery groceries grocerie instamart mart essentials essential').split(' ');
  function parseFood(text) {
    var t = text.toLowerCase();
    var pm = t.match(/(?:under|below|less than|within|upto|up to|max|budget(?: of)?|around)\s*(?:rs\.?|₹|inr)?\s*(\d{2,5})/) || t.match(/(?:₹|rs\.?\s*)(\d{2,5})/);
    var nonVeg = /\bnon[\s-]?veg\b/.test(t), veg = !nonVeg && /\b(veg|vegetarian)\b/.test(t), mart = /\b(grocery|groceries|instamart|mart|essentials)\b/.test(t);
    var kw = t.replace(/[^a-z\s]/g, ' ').split(/\s+/).filter(function (w) { return w.length >= 3 && STOP.indexOf(w) < 0; }).map(function (w) { return w.length > 4 && w.slice(-1) === 's' ? w.slice(0, -1) : w; });
    kw = kw.filter(function (w, i) { return kw.indexOf(w) === i; }).slice(0, 4);
    return { maxPrice: pm ? Number(pm[1]) : null, veg: veg, nonVeg: nonVeg, mart: mart, kw: kw };
  }
  function searchDishes(q, any) {
    var rows = [];
    D.vendors.forEach(function (v) {
      if (v.is_active === 0 || (q.mart && v.mode !== 'mart')) return;
      v.products.forEach(function (p) {
        if (p.is_available === 0) return;
        if (q.maxPrice && p.price > q.maxPrice) return;
        if (q.veg && !p.veg) return; if (q.nonVeg && p.veg) return;
        var hay = (p.name + ' ' + (p.description || '') + ' ' + p.category + ' ' + v.category + ' ' + v.name).toLowerCase();
        var hits = q.kw.map(function (k) { return hay.indexOf(k) >= 0; });
        if (q.kw.length && !(any ? hits.some(Boolean) : hits.every(Boolean))) return;
        rows.push({ p: p, v: v });
      });
    });
    rows.sort(function (a, b) { return b.v.rating - a.v.rating || a.p.price - b.p.price; });
    return rows.slice(0, 5);
  }
  function recommend(text, force) {
    var q = parseFood(text), has = q.kw.length || q.maxPrice || q.veg || q.nonVeg || q.mart;
    if (!has && !force) return null;
    var rows = searchDishes(q, false); if (!rows.length && q.kw.length > 1) rows = searchDishes(q, true);
    if (!rows.length) return null;
    var bits = []; if (q.veg) bits.push('veg'); if (q.nonVeg) bits.push('non-veg');
    return { reply: 'Here are some ' + (bits.length ? bits.join(' ') + ' picks' : 'picks') + (q.maxPrice ? ' under ₹' + q.maxPrice : '') + (q.kw.length ? ' for "' + q.kw.join(' ') + '"' : '') + ' — tap one to open the menu:',
      items: rows.map(function (r) { return { text: r.p.name + ' — ' + inr(r.p.price) + ' · ' + r.v.name, url: '#/vendor/' + r.v.id }; }) };
  }
  function has(text, list) { return list.some(function (p) { return new RegExp('\\b' + p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + (p.length <= 3 ? '\\b' : '')).test(text); }); }
